/// Entry point called once from `main()` before `runApp`.
///
/// Two layers of registration:
///   1. [setUpGeneralDependencies] — manual registrations for services that
///      can't be reached by `@injectable` (private constructors, factory
///      singletons, things owned by a package we don't control, …).
///   2. `injector.init()` — generated by `injectable_generator`. Picks up
///      every `@injectable` / `@lazySingleton` / `@singleton` annotation in
///      `lib/` and wires them automatically.
///
/// Put cubits and use-cases on the annotation track. Keep this file for
/// pure infrastructure (dio, storage, notification stack, queues, etc.).
@InjectableInit(
  initializerName: 'init',
  preferRelativeImports: true,
  asExtension: true,
)
void setUpServiceLocator() {
  if (_serviceLocatorConfigured) return;
  setUpGeneralDependencies();
  injector.init();
  _serviceLocatorConfigured = true;
}

bool _serviceLocatorConfigured = false;

void setUpGeneralDependencies() {
  // Infrastructure singletons that have private constructors / factory
  // patterns — `@injectable` can't reach them, so we wire by hand.
  //
  injector.registerLazySingleton<DioClient>(() => DioClient());
  injector.registerLazySingleton<RequestCancellationManager>(
    () => RequestCancellationManager(),
  );
  injector.registerLazySingleton<OfflineQueueManager>(
    () => OfflineQueueManager(),
  );
  // Cross-cutting cubits not driven by features.
  injector.registerLazySingleton<ConnectivityCubit>(() => ConnectivityCubit());
  injector.registerLazySingleton<OfflineQueueCubit>(() => OfflineQueueCubit());
}

/// Exposes the private-constructor token store to code generation while
/// preserving [TokenStorage.instance] as the only runtime instance.
@module
abstract class CoreInfrastructureModule {
  @lazySingleton
  TokenStorage get tokenStorage => TokenStorage.instance;
}
