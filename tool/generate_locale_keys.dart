import 'dart:convert';
import 'dart:io';

const _arabicPath = 'assets/translations/ar.json';
const _englishPath = 'assets/translations/en.json';
const _outputPath = 'lib/src/config/language/locale_keys.g.dart';

Future<void> main() async {
  final arabic = await _readFlatTranslations(_arabicPath);
  final english = await _readFlatTranslations(_englishPath);

  final missingInEnglish = arabic.keys.toSet().difference(english.keys.toSet());
  final missingInArabic = english.keys.toSet().difference(arabic.keys.toSet());
  if (missingInEnglish.isNotEmpty || missingInArabic.isNotEmpty) {
    stderr
      ..writeln('Translation keys are not aligned.')
      ..writeln('Missing in English: ${missingInEnglish.toList()..sort()}')
      ..writeln('Missing in Arabic: ${missingInArabic.toList()..sort()}');
    exitCode = 1;
    return;
  }

  final output = StringBuffer()
    ..writeln('// GENERATED CODE - DO NOT MODIFY BY HAND')
    ..writeln('// Generated by: dart run tool/generate_locale_keys.dart')
    ..writeln()
    ..writeln("import 'package:easy_localization/easy_localization.dart';")
    ..writeln()
    ..writeln('abstract final class LocaleKeys {');

  for (final key in arabic.keys) {
    final identifier = _camelCase(key);
    output
      ..writeln("  static const String _$identifier = '$key';")
      ..writeln('  static String get $identifier => _$identifier.tr();')
      ..writeln();
  }

  output.writeln('}');
  await File(_outputPath).writeAsString(output.toString());
  stdout.writeln('Generated ${arabic.length} localized keys at $_outputPath.');
}

Future<Map<String, Object?>> _readFlatTranslations(String path) async {
  final value = jsonDecode(await File(path).readAsString());
  if (value is! Map<String, dynamic>) {
    throw FormatException('$path must contain a JSON object.');
  }
  for (final entry in value.entries) {
    if (entry.value is Map || entry.value is List) {
      throw FormatException(
        '$path contains nested key ${entry.key}; this generator expects flat keys.',
      );
    }
  }
  return value.cast<String, Object?>();
}

String _camelCase(String key) {
  final parts = key.split('_').where((part) => part.isNotEmpty).toList();
  if (parts.isEmpty) {
    throw FormatException('Translation keys cannot be empty.');
  }
  return parts.first +
      parts.skip(1).map((part) {
        return '${part[0].toUpperCase()}${part.substring(1)}';
      }).join();
}
